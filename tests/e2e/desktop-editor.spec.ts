/**
 * End-to-end tests for the desktop renderer.
 *
 * Each test launches the real Electron app (built main + preload + renderer)
 * against a fresh, isolated user-data directory, drives it through the same
 * command bridge the UI uses, and asserts on the rendered DOM. Nothing here
 * reaches into the model directly -- every mutation goes through a command id,
 * which is exactly the contract the UI is built on.
 */

import { _electron as electron, type ElectronApplication, type Page } from 'playwright';
import { test, expect } from '@playwright/test';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { mkdtempSync, rmSync } from 'node:fs';

const electronMain = join(process.cwd(), 'apps', 'desktop', 'dist', 'main', 'index.js');

/**
 * Launch the app against a throwaway workspace and wait until it is actually
 * ready for input.
 *
 * `firstWindow()` resolving only means a window object exists. It says nothing
 * about the renderer having mounted, which is why pressing a key immediately
 * after it was intermittently a no-op: the chord was dispatched into a document
 * with no listener attached yet. Waiting for the sidebar is the smallest thing
 * that genuinely proves React has rendered.
 *
 * The window is focused explicitly for the same reason. Keyboard events go to
 * the focused window, and a freshly created one is not reliably it.
 */
async function launch(): Promise<{ app: ElectronApplication; window: Page; dirs: string[] }> {
  // Two directories, not one: the workspace holds the documents, the profile
  // holds Chromium state. Isolating only the profile left the tests writing
  // into whatever workspace the app defaults to -- the documentation screenshot
  // ended up showing a sidebar of 1606 pages left by earlier runs.
  const dir = mkdtempSync(join(tmpdir(), 'ow-e2e-'));
  const profile = mkdtempSync(join(tmpdir(), 'ow-profile-'));
  const app = await electron.launch({
    args: [electronMain],
    env: { ...process.env, OW_WORKSPACE: dir, OW_USER_DATA: profile },
  });
  const window = await app.firstWindow();
  await window.bringToFront();
  await expect(window.locator('.ow-sidebar')).toBeVisible();
  // The renderer has mounted and the initial state has arrived over the bridge.
  await expect(window.locator('.ow-app')).toBeVisible();
  return { app, window, dirs: [dir, profile] };
}

/** Close and clean up, tolerating an app that is already gone. */
async function shutdown(app: ElectronApplication | undefined, dirs: string[]): Promise<void> {
  await app?.close().catch(() => {});
  for (const dir of dirs) rmSync(dir, { recursive: true, force: true });
}

test.describe('desktop editor', () => {
  test('Ctrl+N creates and opens a page, then typing fills its block', async ({
    page: _page,
  }) => {
    // Isolated workspace so one test cannot leak state into another or into the
    // real user workspace.
    const { app, window, dirs } = await launch();
    try {
      // A fresh workspace has no pages: the empty state shows a "New page"
      // button in the sidebar and "No page selected." in the page view.
      await expect(
        window.getByRole('button', { name: /New page/ })
      ).toBeVisible();

      // Ctrl+N creates a page and opens it (App.tsx wires the chord to exactly
      // that pair of commands). The opened page starts with one empty block.
      await window.keyboard.press('Control+n');

      const editor = window.getByRole('textbox', { name: 'paragraph' }).first();
      await expect(editor).toBeVisible();

      await editor.click();
      await editor.type('Hello Openfield');

      await expect(editor).toHaveText('Hello Openfield');

      // Screenshot generated by the app's own e2e harness.
      await window.screenshot({ path: 'docs/images/e2e-editor.png', fullPage: true });
    } finally {
      await shutdown(app, dirs);
    }
  });

  test('the sidebar New page button opens the page it creates', async () => {
    const { app, window, dirs } = await launch();
    try {
      await window.keyboard.press('Control+n');
      const editor = window.getByRole('textbox', { name: 'paragraph' }).first();
      await editor.click();
      await editor.type('First page');

      // The button and the chord are the same promise to the user: a page is
      // made and it is the one being edited. Creating it without opening it
      // leaves an "Untitled" row in a list, which reads as a dead button.
      await window.locator('.ow-new-page').click();
      await expect(window.locator('.ow-block-text')).toHaveCount(1);
      await expect(window.locator('.ow-block-text').first()).toHaveText('');
      await expect(window.getByRole('textbox', { name: 'Page title' })).toHaveText('');
    } finally {
      await shutdown(app, dirs);
    }
  });

  test('the page title can be renamed by clicking it and typing', async () => {
    const { app, window, dirs } = await launch();
    try {
      await window.keyboard.press('Control+n');
      const title = window.getByRole('textbox', { name: 'Page title' });
      // A press on the page margin starts a rubber-band selection, and the title
      // is not a block, so this click used to be swallowed: the title could not
      // be focused with the mouse at all.
      await title.click();
      await window.keyboard.type('Field notes');
      await window.keyboard.press('Enter');
      await expect(title).toHaveText('Field notes');
      await expect(window.locator('.ow-sidebar')).toContainText('Field notes');
      // The title is a field of its own. It used to be copied into the first
      // block as well, so a page showed its own name twice.
      await expect(window.locator('.ow-block-text').first()).toHaveText('');
    } finally {
      await shutdown(app, dirs);
    }
  });

  test('undo and redo stay consistent with the model', async ({ page: _page }) => {
    const { app, window, dirs } = await launch();
    try {
      await window.keyboard.press('Control+n');

      const editor = window.getByRole('textbox', { name: 'paragraph' }).first();
      await expect(editor).toBeVisible();
      await editor.click();

      // One input event, not three keystrokes. Consecutive keystrokes coalesce
      // into one undo step only while they are within 600 ms of each other, so
      // a burst typed on a loaded machine can end up as two steps -- which is
      // the model behaving correctly and the test measuring the host instead.
      // The burst rule itself is covered by the model's own coalescing test.
      await editor.fill('one');
      await expect(editor).toHaveText('one');

      // Ctrl+Z routes through history.undo, not the browser stack, so the
      // model and the DOM stay in step.
      await window.keyboard.press('Control+z');
      await expect(editor).toHaveText('');

      // Ctrl+Y routes through history.redo.
      await window.keyboard.press('Control+y');
      await expect(editor).toHaveText('one');
    } finally {
      await shutdown(app, dirs);
    }
  });
});
